# Consolidates usuarios_activos (the institute's true current-members
# snapshot - see memory 2026-10-15) onto the 941 member records already
# loaded from personal_CBGP_FINAL_MERGED.csv. For each of the 225 active
# people: if their normalized DNI already has a record (149 do), this
# becomes their new CURRENT version (oldid: that primary_id) - the
# chronological-last change-log row it previously had is pushed into
# history automatically, same SCD mechanism as personnel_loader.rb. The
# other 76 (never had a change logged, including the user himself) get a
# brand-new standalone record with no prior history.
#
# Column headers in usuarios_activos are Sara's own raw Spanish labels, NOT
# questionclass fragments - every mapping below was confirmed either by an
# exact value-shape match against the live ontology's real answer ids, or
# (for member_category/member_research_area_group) empirically derived by
# joining usuarios_historico to the already-loaded personal_CBGP_FINAL_MERGED
# on (DNI, start date) and taking the majority ontology code per Spanish
# label - see the session this was built in. Anything that doesn't resolve
# goes to CURATION, written under Desktop/CBGP Databases/For Curation/.

# Generated by build_derived_inputs.py, not a session scratch file - this
# script's whole output must be regeneratable from source files + scripts
# alone (per the user, 2026-10-15), with nothing depending on a particular
# Claude session's temp directory surviving.
DERIVED_DIR = '/home/osboxes/Desktop/CBGP Databases'.freeze
CURATION_DIR = '/home/osboxes/Desktop/CBGP Databases/For Curation'.freeze

def normalize_dni(value)
  value.to_s.strip.upcase.gsub(/[\s-]/, '')
end

def normalize_person_name(given, surname)
  unaccent("#{given} #{surname}").downcase.gsub(/[.-]/, ' ').gsub(/\s+/, ' ').strip
end

# ---- existing current-store identity (DNI -> primary_id) ----
def load_dni_to_primary_id
  graphs = execute_search(dataset_type: 'member', broad: true) || []
  return {} if graphs.empty?

  raw = fetch_datasets_raw_data(graph_uris: graphs, database: 'member')
  map = {}
  raw.each do |d|
    dni = normalize_dni(d[:member_dni_nie_pas])
    next if dni.empty?

    map[dni] = d[:dataset].to_s.split('/').last
  end
  map
end

# ---- lookup tables, all keyed from files already verified this session ----
def load_label_dictionary(path)
  dict = {}
  CSV.foreach(path, headers: true) { |r| dict[r['label']] = r['code'] }
  dict
end

CATEGORY_DICTIONARY = load_label_dictionary("#{DERIVED_DIR}/category_dictionary.csv")
RESEARCH_AREA_DICTIONARY = load_label_dictionary("#{DERIVED_DIR}/research_area_dictionary.csv")

ID_NAME_TO_IDS = Hash.new { |h, k| h[k] = Set.new }
CSV.foreach('/home/osboxes/Desktop/CBGP Databases/id_CBGP.csv', headers: true) do |r|
  next if r['member_cbgp_id'].to_s.strip.empty?

  ID_NAME_TO_IDS[normalize_person_name(r['member_name'], r['member_surnames'])] << r['member_cbgp_id'].strip
end

ORCID_NAME_TO_ORCID = {}
CSV.foreach("#{DERIVED_DIR}/orcid_codes.csv", headers: true) do |r|
  next if r['orcid'].to_s.strip.empty?

  ORCID_NAME_TO_ORCID[normalize_person_name(r['given'], r['surname'])] = r['orcid'].strip
end

GENDER_MAP = { 'Mujer' => 'female', 'Hombre' => 'male' }.freeze
# Built from the top 15 of 21 distinct values on the first pass - missed
# the long tail (6 single-occurrence values, incl. the user's own "Canada")
# entirely because of that arbitrary cutoff, not because they're missing
# from the ontology (all 6 verified present: egypt/usa/germany/belgium/
# netherlands/canada). Now the full 21.
NATIONALITY_MAP = {
  'España' => 'spain', 'Italia' => 'italy', 'China' => 'china', 'Polonia' => 'poland',
  'Brasil' => 'brazil', 'Argentina' => 'argentina', 'Francia' => 'france', 'Chile' => 'chile',
  'Ecuador' => 'ecuador', 'Marruecos' => 'morocco', 'Suecia' => 'sweden', 'Croacia' => 'croatia',
  'India' => 'india', 'Tunisia' => 'tunisia', 'Colombia' => 'colombia',
  'Egipto' => 'egypt', 'Estados Unidos' => 'usa', 'Alemania' => 'germany',
  'Belgica' => 'belgium', 'Holanda' => 'netherlands', 'Canada' => 'canada'
}.freeze
INSTITUTION_MAP = { 'UPM' => 'UPM', 'CSIC' => 'CSIC', 'INIA' => 'INIA', 'CBGP' => 'CBGP', 'OTROS' => 'institution_other' }.freeze
INSTITUTIONAL_EMAIL_DOMAINS = %w[csic.es upm.es alumnos.upm.es inia.es cbgp.upm.es].freeze

def institutional_email?(email)
  domain = email.to_s.split('@').last.to_s.downcase
  INSTITUTIONAL_EMAIL_DOMAINS.any? { |d| domain.end_with?(d) }
end

def code5_for(letter)
  return nil if letter.to_s.strip.empty?

  candidate = "5#{letter.strip}"
  %w[5A 5B 5C 5D 5E 5F 5G].include?(candidate) ? candidate : nil
end

def code10_for(letter)
  letter = letter.to_s.strip
  return nil if letter.empty?
  return 'code10_none' if letter == 'Ninguno'

  candidate = "10#{letter}"
  %w[10A 10B 10C 10D 10E 10F 10G].include?(candidate) ? candidate : nil
end

def yes_no(value, yes_code, no_code)
  case value.to_s.strip
  when 'SI' then yes_code
  when 'NO' then no_code
  end
end

CURATION = []

dni_to_primary_id = load_dni_to_primary_id
warn "Existing current-store records indexed: #{dni_to_primary_id.size}"

rows = CSV.read("#{DERIVED_DIR}/activos_export.csv", headers: true).map(&:to_h)
created = 0
updated = 0

rows.each do |row|
  dni = normalize_dni(row['DNI/NIE/PAS'])
  if dni.empty?
    CURATION << { dni: '(blank)', issue: 'blank DNI in usuarios_activos', detail: "#{row['Nombre']} #{row['Apellidos']}" }
    next
  end

  name_key = normalize_person_name(row['Nombre'], row['Apellidos'])

  category_label = row['Categoría Según Reglamento'].to_s.strip
  category_code = CATEGORY_DICTIONARY[category_label]
  CURATION << { dni: dni, issue: 'unmapped category', detail: category_label } if category_code.nil? && !category_label.empty?

  rag_label = row['Grupo'].to_s.strip
  rag_code = RESEARCH_AREA_DICTIONARY[rag_label]
  CURATION << { dni: dni, issue: 'unmapped research_area_group', detail: rag_label } if rag_code.nil? && !rag_label.empty?

  gender_code = GENDER_MAP[row['Sexo'].to_s.strip]
  CURATION << { dni: dni, issue: 'unmapped gender', detail: row['Sexo'] } if gender_code.nil? && !row['Sexo'].to_s.strip.empty?

  nationality_code = NATIONALITY_MAP[row['Nacionalidad'].to_s.strip]
  CURATION << { dni: dni, issue: 'unmapped nationality', detail: row['Nacionalidad'] } if nationality_code.nil? && !row['Nacionalidad'].to_s.strip.empty?

  institution_code = INSTITUTION_MAP[row['Institucion'].to_s.strip]

  code5 = code5_for(row['Articulo 5'])
  CURATION << { dni: dni, issue: 'unmapped Articulo 5', detail: row['Articulo 5'] } if code5.nil? && !row['Articulo 5'].to_s.strip.empty?

  code10 = code10_for(row['Articulo 10'])
  CURATION << { dni: dni, issue: 'unmapped Articulo 10', detail: row['Articulo 10'] } if code10.nil? && !row['Articulo 10'].to_s.strip.empty?

  emails = [row['E-Mail1'], row['Email2']].map { |e| e.to_s.strip }.reject(&:empty?).uniq
  institutional_mail = emails.find { |e| institutional_email?(e) }
  personal_mail = emails.find { |e| !institutional_email?(e) } || (emails - [institutional_mail]).first

  cbgp_id = row['ID_Unico'].to_s.strip
  cbgp_id = nil if cbgp_id.empty?
  if cbgp_id.nil?
    found_ids = ID_NAME_TO_IDS[name_key]
    cbgp_id = found_ids.first if found_ids.size == 1
  end

  orcid = ORCID_NAME_TO_ORCID[name_key]

  ds = CBGP::Dataset.new(type: 'member')
  existing_primary_id = dni_to_primary_id[dni]
  ds.primary_id = existing_primary_id || SecureRandom.uuid

  ds.name = row['Nombre'] unless row['Nombre'].to_s.strip.empty?
  ds.surname = row['Apellidos'] unless row['Apellidos'].to_s.strip.empty?
  ds.dni_nie_pas = dni
  ds.gender = gender_code if gender_code
  ds.nationality = nationality_code if nationality_code
  ds.office = row['Despacho'] unless row['Despacho'].to_s.strip.empty?
  ds.lab = row['Laboratorio'] unless row['Laboratorio'].to_s.strip.empty?
  ds.office_phone_number = row['Teléfono Despacho'] unless row['Teléfono Despacho'].to_s.strip.empty?
  ds.lab_phone_number = row['Telefono Laboratorio'] unless row['Telefono Laboratorio'].to_s.strip.empty?
  ds.personal_phone_number = row['Teléfono'] unless row['Teléfono'].to_s.strip.empty?
  ds.personal_mail = personal_mail if personal_mail
  ds.institutional_mail = institutional_mail if institutional_mail
  ds.start_date = row['Fecha de Alta'] unless row['Fecha de Alta'].to_s.strip.empty?
  ds.estimated_end_date = row['Fecha Estimada'] unless row['Fecha Estimada'].to_s.strip.empty?
  ds.funding_comments = row['Financiacion'] unless row['Financiacion'].to_s.strip.empty?
  ds.category = category_code if category_code
  ds.research_area = rag_code if rag_code
  ds.institution = institution_code if institution_code
  ds.status = 'active'
  permanence = yes_no(row['Plaza Fija'], 'permanent_position_yes', 'permanent_position_no')
  ds.permanence = permanence if permanence
  pi = yes_no(row['Jefe de Grupo / servicio'], 'pi_yes', 'pi_no')
  ds.pi = pi if pi
  consejo = yes_no(row['Consejo'], 'consejo_yes', 'consejo_no')
  ds.consejo = consejo if consejo
  cluster = yes_no(row['Cluster'], 'cluster_yes', 'cluster_no')
  ds.cluster = cluster if cluster
  ds.code_5 = code5 if code5
  ds.code_10 = code10 if code10
  ds.thesis_date = row['Año Tesis'] unless row['Año Tesis'].to_s.strip.empty?
  ds.cbgp_id = cbgp_id if cbgp_id
  ds.orcid = orcid if orcid

  oldid = existing_primary_id
  CBGP::Dataset.write_to_db(dataset: ds, oldid: oldid)
  oldid ? (updated += 1) : (created += 1)
end

curation_path = "#{CURATION_DIR}/activos_consolidation_curation.csv"
CSV.open(curation_path, 'w') do |csv|
  csv << %w[dni issue detail]
  CURATION.each { |c| csv << [c[:dni], c[:issue], c[:detail]] }
end

puts
puts "Done. #{updated} existing records updated to the activos current snapshot, #{created} brand-new records created."
puts "#{CURATION.size} items need curation - see #{curation_path}"
